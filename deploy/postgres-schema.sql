-- PostgreSQL schema: no personal data.
CREATE TABLE IF NOT EXISTS portal_backups (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,file TEXT UNIQUE NOT NULL,payload TEXT NOT NULL,bytes INTEGER NOT NULL,created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS "users" (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         TEXT UNIQUE,
    password      TEXT NOT NULL,
    name          TEXT NOT NULL,
    role          TEXT NOT NULL CHECK(role IN ('student','faculty','admin')),
    department    TEXT,
    course        TEXT,
    student_id    TEXT,
    faculty_id    TEXT,
    specialization TEXT,
    avatar        TEXT,
    created_at    TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila','YYYY-MM-DD HH24:MI:SS'))
  , is_active INTEGER NOT NULL DEFAULT 1, contact_number TEXT NOT NULL DEFAULT '', contact_email TEXT NOT NULL DEFAULT '', consultation_location TEXT NOT NULL DEFAULT '', meeting_link TEXT NOT NULL DEFAULT '', consultation_instructions TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS appointments (
      id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id      INTEGER NOT NULL,
      faculty_id      INTEGER NOT NULL,
      date            TEXT NOT NULL,
      time_slot       TEXT NOT NULL,
      end_time        TEXT NOT NULL,
      purpose         TEXT NOT NULL,
      remarks         TEXT DEFAULT '',
      status          TEXT DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected','completed','cancelled','checked-in','no-show')),
      faculty_remarks TEXT DEFAULT '',
      checkin_code    TEXT,
      checkin_time    TEXT,
      queue_number    INTEGER,
      queue_status    TEXT DEFAULT 'waiting' CHECK(queue_status IN ('waiting','next','serving','completed','skipped')),
      created_at      TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila','YYYY-MM-DD HH24:MI:SS')),
      updated_at      TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila','YYYY-MM-DD HH24:MI:SS')), cancel_reason TEXT NOT NULL DEFAULT '',
      FOREIGN KEY (student_id) REFERENCES users(id),
      FOREIGN KEY (faculty_id) REFERENCES users(id)
    );
CREATE TABLE IF NOT EXISTS faculty_schedules (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id    INTEGER NOT NULL,
    day_of_week   INTEGER NOT NULL,          -- 0=Sun … 6=Sat
    start_time    TEXT NOT NULL,
    end_time      TEXT NOT NULL,
    is_available  INTEGER DEFAULT 1, slot_duration INTEGER NOT NULL DEFAULT 15, specific_date TEXT,
    FOREIGN KEY (faculty_id) REFERENCES users(id) ON DELETE CASCADE
  );
CREATE TABLE IF NOT EXISTS notifications (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL,
    title       TEXT NOT NULL,
    message     TEXT NOT NULL,
    type        TEXT DEFAULT 'info',
    related_id  INTEGER,
    is_read     INTEGER DEFAULT 0,
    created_at  TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila','YYYY-MM-DD HH24:MI:SS')),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
  );
CREATE TABLE IF NOT EXISTS blocked_dates (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id  INTEGER NOT NULL,
    date        TEXT NOT NULL,
    reason      TEXT DEFAULT '', start_time TEXT, end_time TEXT,
    FOREIGN KEY (faculty_id) REFERENCES users(id) ON DELETE CASCADE
  );
CREATE TABLE IF NOT EXISTS departments (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS audit_log (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id INTEGER, action TEXT NOT NULL, target_id INTEGER, details TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila','YYYY-MM-DD HH24:MI:SS')));
CREATE TABLE IF NOT EXISTS reschedule_requests (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, appointment_id INTEGER NOT NULL REFERENCES appointments(id), requested_by INTEGER NOT NULL REFERENCES users(id),
      original_date TEXT NOT NULL,original_start TEXT NOT NULL,original_end TEXT NOT NULL,
      proposed_date TEXT NOT NULL,proposed_start TEXT NOT NULL,proposed_end TEXT NOT NULL,reason TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected','withdrawn','superseded')),
      response_note TEXT NOT NULL DEFAULT '',created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila','YYYY-MM-DD HH24:MI:SS')),responded_at TEXT);
CREATE TABLE IF NOT EXISTS appointment_events (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,appointment_id INTEGER NOT NULL REFERENCES appointments(id),actor_id INTEGER REFERENCES users(id),action TEXT NOT NULL,details TEXT NOT NULL DEFAULT '{}',created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila','YYYY-MM-DD HH24:MI:SS')));
CREATE TABLE IF NOT EXISTS reminder_deliveries (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,appointment_id INTEGER NOT NULL REFERENCES appointments(id),scheduled_for TEXT NOT NULL,lead_minutes INTEGER NOT NULL,user_id INTEGER NOT NULL REFERENCES users(id),sent_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila','YYYY-MM-DD HH24:MI:SS')),UNIQUE(appointment_id,scheduled_for,lead_minutes,user_id));
CREATE TABLE IF NOT EXISTS sessions (sid TEXT PRIMARY KEY,data TEXT NOT NULL,expires BIGINT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS student_number_unique ON users(lower(trim(student_id))) WHERE role='student';
CREATE UNIQUE INDEX IF NOT EXISTS faculty_number_unique ON users(lower(trim(faculty_id))) WHERE role='faculty';
CREATE UNIQUE INDEX IF NOT EXISTS department_name_unique ON departments(lower(name));
CREATE UNIQUE INDEX IF NOT EXISTS one_pending_reschedule ON reschedule_requests(appointment_id) WHERE status='pending';
CREATE INDEX IF NOT EXISTS appointments_faculty_date ON appointments(faculty_id,date,status);
CREATE INDEX IF NOT EXISTS appointments_student_date ON appointments(student_id,date,status);
CREATE INDEX IF NOT EXISTS notifications_user ON notifications(user_id,is_read);
CREATE INDEX IF NOT EXISTS session_expiry ON sessions(expires);
